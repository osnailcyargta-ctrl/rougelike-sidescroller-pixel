const CACHE = new Map();
export const CHAR_W = 5, CHAR_H = 7, SPACING = 1;

function glyph(ch) {
  const g = G[ch] || G['?'];
  if (!CACHE.has(g)) CACHE.set(g, g.split(','));
  return CACHE.get(g);
}

export function textWidth(str, scale = 1) {
  return str.length * (CHAR_W + SPACING) * scale - SPACING * scale;
}

export function drawText(ctx, str, x, y, color = '#fff', scale = 1, align = 'left') {
  str = String(str).toUpperCase();
  let px = Math.round(x);
  const w = textWidth(str, scale);
  if (align === 'center') px = Math.round(x - w / 2);
  else if (align === 'right') px = Math.round(x - w);
  const py = Math.round(y);
  ctx.fillStyle = color;
  for (let i = 0; i < str.length; i++) {
    const rows = glyph(str[i]);
    const ox = px + i * (CHAR_W + SPACING) * scale;
    for (let r = 0; r < CHAR_H; r++) {
      const row = rows[r];
      let run = 0;
      for (let c = 0; c <= CHAR_W; c++) {
        if (c < CHAR_W && row[c] === '1') { run++; continue; }
        if (run > 0) {
          ctx.fillRect(ox + (c - run) * scale, py + r * scale, run * scale, scale);
          run = 0;
        }
      }
    }
  }
  return w;
}

export function drawTextShadow(ctx, str, x, y, color, scale = 1, align = 'left', shadow = '#000000cc') {
  drawText(ctx, str, x + scale, y + scale, shadow, scale, align);
  return drawText(ctx, str, x, y, color, scale, align);
}
